// 获取带 alpha 的颜色（用于地图显示）
export function getDatasetColorWithAlpha(index: number, alpha: number = 0.9): number[] {
  const color = DATASET_COLORS[index % DATASET_COLORS.length];
  return [...color, alpha];
}

// 获取颜色字符串（用于图例等显示）
export function getDatasetColorString(index: number): string {
  const color = DATASET_COLORS[index % DATASET_COLORS.length];
  return `rgb(${color[0]}, ${color[1]}, ${color[2]})`;
}